/**
 * Showcase event on staging (plan docs/superpowers/plans/2026-10-26-bot-cup-admin-showcase.md §3.5): 100 synthetic teams
 * with a ready submission each, written straight into the staging D1, then played out by the simulated runner
 * (BOT_CUP_RUNNER_SIMULATE=true) through the normal runner API, every game replayed by the Worker before it counts.
 *
 *   node scripts/bot-cup/showcase.mjs seed [--teams 100] [--freeze-in 1] [--event showcase-<stamp>]
 *   node scripts/bot-cup/showcase.mjs deploy          both showcase Workers, pointed at the seeded event
 *   node scripts/bot-cup/showcase.mjs drive [--admin <origin>]   presses every organiser step until the event ends
 *
 * Submissions are append-only (a trigger refuses DELETE), so a showcase is never reset: each `seed` makes a new event id
 * and `deploy` points the Workers at it. The current one is in var/bot-cup/showcase/current.json. Submissions are inserted
 * as ready, not uploaded: an upload of 100 near-identical files would flag every team as a copy of the template.
 * The bot code is never run in a showcase; its first lines carry the strength the simulated runner plays at.
 * Staging only.
 */
import crypto from "node:crypto";
import { spawnSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { nameKey, normalizeSource } from "../../packages/bot-cup-core/src/index.mjs";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const DIR = path.join(ROOT, "var/bot-cup/showcase");
const CURRENT = path.join(DIR, "current.json");
const DATABASE = "ottv2-bot-cup-staging";
const ADMIN_ORIGIN = "https://ottv2-bot-cup-admin-showcase.opticsquang.workers.dev";
const DAY = 24 * 60 * 60 * 1000;

const FIRST = ["Sao", "Rồng", "Hổ", "Đại Bàng", "Phượng", "Sóng", "Gió", "Lửa", "Mây", "Sấm"];
const SECOND = ["Băng", "Xanh", "Đỏ", "Vàng", "Bạc", "Lam", "Đêm", "Mai", "Biển", "Núi"];

function option(name, fallback = null) {
  const index = process.argv.indexOf(`--${name}`);
  return index > 0 ? process.argv[index + 1] : fallback;
}

const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms));
const sqlText = (value) => `'${String(value).replace(/'/g, "''")}'`;

/** A deterministic shuffle, so the same seed gives the same strengths. */
function mulberry32(seed) {
  let state = seed >>> 0;
  return () => {
    state = (state + 0x6d2b79f5) >>> 0;
    let t = state;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/**
 * The synthetic teams: names "Đội <first> <second>", strengths spread over 0.55..1 (shuffled), so about 3 in 10 fall
 * below ~0.68 and miss the gate (4 points from 6 games against the easy house bot).
 */
export function showcaseTeams(count = 100, seed = 2026) {
  if (!Number.isInteger(count) || count < 4 || count > FIRST.length * SECOND.length) throw new Error(`--teams must be 4..${FIRST.length * SECOND.length}`);
  const random = mulberry32(seed);
  const strengths = Array.from({ length: count }, (_, index) => 0.55 + (0.45 * index) / (count - 1));
  for (let index = strengths.length - 1; index > 0; index--) {
    const other = Math.floor(random() * (index + 1));
    [strengths[index], strengths[other]] = [strengths[other], strengths[index]];
  }
  return strengths.map((strength, index) => ({
    key: String(index + 1).padStart(3, "0"),
    name: `Đội ${FIRST[Math.floor(index / SECOND.length)]} ${SECOND[index % SECOND.length]}`,
    strength: Math.round(strength * 100) / 100
  }));
}

/** The bot file of a synthetic team. Valid Bot Protocol v1 code, but the simulated runner only reads the strength line. */
export function botSource(team) {
  return `// OTT Bot Cup · bot tổng hợp cho buổi demo 100 đội (scripts/bot-cup/showcase.mjs) · ${team.name}
// ott-showcase strength=${team.strength.toFixed(2)}
// Runner giả lập đọc dòng trên và tự đánh ở mức đó; đoạn mã dưới đây chỉ để bài nộp hợp lệ, không chạy trong demo.
import readline from "node:readline";

readline.createInterface({ input: process.stdin, terminal: false }).on("line", (line) => {
  if (!line.trim()) return;
  const turn = JSON.parse(line);
  if (turn.type !== "turn") return;
  process.stdout.write(JSON.stringify({ protocolVersion: 1, requestId: turn.requestId, move: turn.legalMoves[0] }) + "\\n");
});
`;
}

const sha256 = (data) => crypto.createHash("sha256").update(data).digest("hex");

/** SQL for the event, its teams, captains and one ready submission each (also the team's final submission). */
export function seedSql({ eventId, teams, now, freezeAt }) {
  const config = JSON.stringify({ knockoutSize: 16, showcase: true });
  const lines = [
    `-- Showcase event ${eventId} (generated by scripts/bot-cup/showcase.mjs).`,
    `INSERT INTO events (id, name, mode, phase, registration_opens_at, registration_closes_at, practice_opens_at, code_freeze_at, finals_at, config_json)
VALUES (${sqlText(eventId)}, 'OTT Bot Cup · Demo ${teams.length} đội', 'demo', 'registration', ${now - 3 * DAY}, ${now - DAY}, ${now - 2 * DAY}, ${freezeAt}, ${freezeAt + DAY}, ${sqlText(config)});`
  ];
  teams.forEach((team, index) => {
    const teamId = `${eventId}-t${team.key}`;
    const mssv = `9900${team.key.padStart(4, "0")}`;
    const source = botSource(team);
    const bytes = Buffer.from(source, "utf8");
    const submissionId = crypto.randomUUID();
    const hash = sha256(bytes);
    // Spread over the last day: the upload time is the final tie-break (plan §7.5).
    const createdAt = now - DAY + index * 60_000;
    lines.push(
      `INSERT INTO teams (id, event_id, handle, display_name, display_key, kind, status, captain_mssv, password_hash, created_at, verified_at, active_at)
VALUES (${sqlText(teamId)}, ${sqlText(eventId)}, ${sqlText(`sc-${team.key}`)}, ${sqlText(team.name)}, ${sqlText(nameKey(team.name))}, 'solo', 'active', ${sqlText(mssv)}, 'disabled', ${createdAt}, ${createdAt}, ${createdAt});`,
      `INSERT INTO members (event_id, mssv, team_id, full_name, email, role, status, show_name, consent_at, created_at, confirmed_at)
VALUES (${sqlText(eventId)}, ${sqlText(mssv)}, ${sqlText(teamId)}, 'Thành viên demo', ${sqlText(`showcase-${team.key}@ottcup.test`)}, 'captain', 'confirmed', 0, ${createdAt}, ${createdAt}, ${createdAt});`,
      `INSERT OR IGNORE INTO submission_sources (sha256, content, size, created_at) VALUES (${sqlText(hash)}, X'${bytes.toString("hex")}', ${bytes.length}, ${createdAt});`,
      `INSERT INTO submissions (id, event_id, team_id, seq, language, filename, size, sha256, normalized_hash, created_at, status, check_log)
VALUES (${sqlText(submissionId)}, ${sqlText(eventId)}, ${sqlText(teamId)}, 1, 'node', 'bot.mjs', ${bytes.length}, ${sqlText(hash)}, ${sqlText(sha256(normalizeSource(source, "node")))}, ${createdAt}, 'ready', 'Bài demo tổng hợp: không kiểm tra.');`,
      `UPDATE teams SET final_submission_id = ${sqlText(submissionId)} WHERE id = ${sqlText(teamId)};`
    );
  });
  return `${lines.join("\n")}\n`;
}

function wrangler(args) {
  const npx = process.platform === "win32" ? "npx.cmd" : "npx";
  const result = spawnSync(npx, ["wrangler", ...args], { cwd: ROOT, stdio: "inherit", shell: process.platform === "win32" });
  if (result.status !== 0) throw new Error(`wrangler ${args[0]} failed`);
}

function current() {
  if (!fs.existsSync(CURRENT)) throw new Error("no showcase seeded yet: run `showcase.mjs seed` first");
  return JSON.parse(fs.readFileSync(CURRENT, "utf8"));
}

async function seed() {
  const now = Date.now();
  const stamp = new Date(now).toISOString().slice(0, 16).replace(/[-:T]/g, "");
  const eventId = option("event", `showcase-${stamp}`);
  if (!/^showcase-[a-z0-9-]{1,40}$/.test(eventId)) throw new Error("--event must start with showcase-");
  const teams = showcaseTeams(Number(option("teams", "100")));
  const freezeAt = now + Number(option("freeze-in", "1")) * 60 * 1000;
  fs.mkdirSync(DIR, { recursive: true });
  const file = path.join(DIR, `${eventId}.sql`);
  fs.writeFileSync(file, seedSql({ eventId, teams, now, freezeAt }));
  wrangler(["d1", "execute", DATABASE, "--remote", "--env", "showcase", "--config", "apps/bot-cup-api/wrangler.jsonc", "--file", path.relative(ROOT, file)]);
  fs.writeFileSync(CURRENT, JSON.stringify({ eventId, teams: teams.length, codeFreezeAt: freezeAt, seededAt: now }, null, 2));
  console.log(JSON.stringify({ eventId, teams: teams.length, codeFreezeAt: new Date(freezeAt).toISOString() }));
}

async function deploy() {
  const { eventId } = current();
  for (const app of ["bot-cup-api", "bot-cup-admin"]) {
    wrangler(["deploy", "--env", "showcase", "--config", `apps/${app}/wrangler.jsonc`, "--var", `BOT_CUP_EVENT_ID:${eventId}`]);
  }
}


/**
 * Plays the organiser: each step as soon as the server accepts it, the top 4 passing their interviews.
 * @param {(method: string, url: string, json?: object) => Promise<{ status: number, body: any }>} call admin API, signed in
 * @param {{ say?: Function, idle?: () => Promise<void> }} hooks `idle` runs while the server waits (games pending, freeze time)
 */
export async function driveEvent(call, { say = () => {}, idle = () => sleep(5_000) } = {}) {
  const step = (name, extra = {}) => call("POST", `/tournament/${name}`, { reason: "Demo: điều phối tự động", ...extra });
  const WAIT = new Set(["games_pending", "freeze_too_early"]);
  for (;;) {
    const read = await call("GET", "/tournament");
    if (read.status !== 200) throw new Error(`tournament view: ${read.status} ${JSON.stringify(read.body)}`);
    const view = read.body;
    let attempt;
    if (view.phase === "finished") return say("finished", { documents: view.documents.map((doc) => doc.stage) });
    if (view.phase === "registration" || view.phase === "practice") attempt = ["freeze", await step("freeze")];
    else if (view.phase === "frozen") attempt = ["gate-start", await step("gate-start")];
    else if (view.phase === "gate") attempt = ["gate-close", await step("gate-close")];
    else if (view.phase === "qualifying") {
      if (!view.standings.format) attempt = ["qualifying-start", await step("qualifying-start")];
      else {
        const next = await step("swiss-next");
        attempt = next.body.error === "swiss_complete" || next.body.error === "not_swiss" ? ["qualifying-close", await step("qualifying-close")] : ["swiss-next", next];
      }
    } else if (view.phase === "verification") {
      const waiting = view.interviews?.waitingFor ?? [];
      if (waiting.length) attempt = ["interviews", await step("interviews", { teamIds: waiting, result: "pass" })];
      else {
        attempt = ["knockout-start", await step("knockout-start")];
        if (attempt[1].body.error === "knockout_not_possible") attempt = ["finish", await step("finish")];
      }
    } else if (view.phase === "knockout") attempt = ["knockout-advance", await step("knockout-advance")];
    else throw new Error(`unexpected phase ${view.phase}`);

    const [name, result] = attempt;
    if (result.status === 200) say(name, result.body);
    else if (WAIT.has(result.body.error)) await idle();
    else throw new Error(`${name}: ${result.status} ${JSON.stringify(result.body)}`);
  }
}

async function drive() {
  const base = option("admin", ADMIN_ORIGIN);
  const login = await fetch(`${base}/admin-api/login`, { method: "POST", headers: { origin: base, "content-type": "application/json" }, body: "{}" });
  if (login.status !== 200) throw new Error(`demo login ${login.status} ${await login.text()} (is ADMIN_AUTH_MODE=demo?)`);
  const cookie = login.headers.get("set-cookie").split(";")[0];
  const call = async (method, url, json) => {
    const response = await fetch(`${base}/admin-api${url}`, { method, headers: { cookie, ...(json ? { origin: base, "content-type": "application/json" } : {}) }, body: json ? JSON.stringify(json) : undefined });
    return { status: response.status, body: await response.json() };
  };
  const started = Date.now();
  await driveEvent(call, { say: (event, fields = {}) => console.log(JSON.stringify({ at: `${Math.round((Date.now() - started) / 1000)}s`, event, ...fields })) });
}

const invokedDirectly = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (invokedDirectly) {
  const run = { seed, deploy, drive }[process.argv[2]];
  if (!run) {
    console.error("usage: showcase.mjs seed|deploy|drive …");
    process.exit(1);
  }
  run().catch((error) => {
    console.error(error.message);
    process.exit(1);
  });
}
